// tools/floor/gen-const-tables.c — the engine's three lookup tables as const
// data, for a port that keeps them in flash (TABLES_CONST, engine/core/tables.h).
//
// Linked with engine/core/tables.c in its normal (non-const) form, it runs the
// engine's own T_GenerateTables -- the 1993 recipes, the correction stream and
// the TABLES_CRC checksum, which I_Errors on any difference -- and prints the
// result as C initializers.  So the const tables are the canon tables by the
// same proof the shipped build uses at boot, and the TABLES_CONST build checks
// them again when it starts.
//
// usage: gen-const-tables > tables_const.inc
// Copyright (C) 2026, GPL-2.0-or-later.
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>

#include "tables.h"

void I_Error (char* error, ...)
{
    va_list ap;
    va_start (ap, error);
    fputs ("gen-const-tables: ", stderr);
    vfprintf (stderr, error, ap);
    fputc ('\n', stderr);
    va_end (ap);
    exit (1);
}

static void emit (const char* type, const char* name, const char* dim,
                  const int* v, int n, int is_unsigned)
{
    int i;
    printf ("const %s %s[%s] = {", type, name, dim);
    for (i = 0; i < n; i++)
    {
        printf ("%s", i == 0 ? "\n    " : i % 8 ? ", " : ",\n    ");
        if (is_unsigned)
            printf ("%uu", (unsigned) v[i]);
        else
            printf ("%d", v[i]);
    }
    printf ("\n};\n");
}

int main (void)
{
    T_GenerateTables ();
    printf ("// generated by tools/floor/gen-const-tables.c from engine/core/tables.c;"
            " do not edit\n");
    emit ("fixed_t", "finesine", "5*FINEANGLES/4", (const int*) finesine, 5 * FINEANGLES / 4, 0);
    emit ("fixed_t", "finetangent", "FINEANGLES/2", (const int*) finetangent, FINEANGLES / 2, 0);
    emit ("angle_t", "tantoangle", "SLOPERANGE+1", (const int*) tantoangle, SLOPERANGE + 1, 1);
    return 0;
}
