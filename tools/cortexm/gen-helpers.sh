#!/usr/bin/env bash
# tools/cortexm/gen-helpers.sh — a counting wrapper for each libgcc helper.
#
# usage: bash gen-helpers.sh helpers.txt > helpers.S
#
# helpers.txt is the list the Makefile derives (the objects' undefined symbols
# that libgcc defines).  For each helper X the link passes --wrap=X, so every
# call from a compiled object reaches __wrap_X, which bumps cm_hcount[i] and
# TAIL-CALLS __real_X: lr, r0-r3 and the stack are exactly as the caller left
# them, so a helper that reads its caller's lr (thumb1 switch tables,
# __gnu_thumb1_case_*) or returns in r0-r3 (__aeabi_uldivmod) is unaffected.
# Only ip (r12) and the flags change, which the AAPCS lets any call clobber.
# ARMv6-M instructions only: one generator for both builds.
# Copyright (C) 2026, GPL-2.0-or-later.
set -euo pipefail
list="$1"
mapfile -t H < "$list"
[ "${#H[@]}" -gt 0 ] || { echo "gen-helpers.sh: $list names no helper" >&2; exit 1; }
[ "${#H[@]}" -le 32 ] || { echo "gen-helpers.sh: ${#H[@]} helpers, NH_MAX is 32 (cm_main.c)" >&2; exit 1; }
cat <<'EOF'
/* generated by tools/cortexm/gen-helpers.sh — do not edit */
    .syntax unified
    .thumb
    .text
EOF
i=0
for h in "${H[@]}"; do
    cat <<EOF
    .thumb_func
    .global __wrap_$h
__wrap_$h:
    push {r4, r5}
    ldr  r4, =cm_hcount + $((i * 4))
    ldr  r5, [r4]
    adds r5, #1
    str  r5, [r4]
    ldr  r4, =__real_$h
    mov  ip, r4
    pop  {r4, r5}
    bx   ip
    .ltorg
EOF
    i=$((i + 1))
done
cat <<EOF
    .bss
    .align 2
    .global cm_hcount
cm_hcount:
    .space $((i * 4))
    .section .rodata
    .align 2
    .global cm_nhelpers
cm_nhelpers:
    .word $i
    .global cm_hnames
cm_hnames:
EOF
for h in "${H[@]}"; do echo "    .word .Lname_$h"; done
for h in "${H[@]}"; do echo ".Lname_$h: .asciz \"$h\""; done
